import assert from 'node:assert/strict';
import { defaults, localRepository, nextActivity, sanitizeSessions, sessionId } from '../lib/learning.ts';
let stored;
globalThis.localStorage = { getItem: () => stored ?? null, setItem: (_, value) => { stored = value; } };
const old = structuredClone(defaults); delete old.sessions; old.progress.exchanges = 7;
stored = JSON.stringify(old);
assert.deepEqual(localRepository.load().sessions, {});
assert.equal(localRepository.load().progress.exchanges, 7);
const data = structuredClone(defaults);
const key = sessionId('Iniciante', 'Emma', 1);
data.sessions[key] = { messages: [{ role: 'user', content: 'Water, please.' }, { role: 'assistant', content: 'Of course!', meaning: 'Claro!' }], draft: 'Thank you', updatedAt: 1 };
localRepository.save(data);
assert.deepEqual(JSON.parse(JSON.stringify(localRepository.load())), data);
assert.deepEqual(nextActivity(data), { index: 1, resume: true, finished: false });
data.preferences.tutor = 'Ethan';
assert.equal(nextActivity(data).resume, false);
data.preferences.tutor = 'Emma';
data.progress.completed = ['Iniciante:1'];
assert.deepEqual(nextActivity(data), { index: 0, resume: false, finished: false });
data.progress.completed = ['Iniciante:0', 'Iniciante:1', 'Iniciante:2'];
assert.equal(nextActivity(data).finished, true);
assert.deepEqual(sanitizeSessions({ [key]: { ...data.sessions[key], messages: [{ role: 'system', content: 'Invalid' }] } }), {});
assert.deepEqual(sanitizeSessions({ [key]: { ...data.sessions[key], draft: 'x'.repeat(2001) } }), {});
assert.deepEqual(sanitizeSessions({ [key]: { ...data.sessions[key], messages: Array(61).fill({ role: 'user', content: 'Hi' }) } }), {});
stored = JSON.stringify({ ...data, sessions: { [key]: null } });
assert.equal(localRepository.load().progress.completed.length, 3);
assert.deepEqual(localRepository.load().sessions, {});
console.log('PASS: migration, persistence, tutor isolation, resume, completion and corrupt-session recovery.');
